import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadSpec, parseOperations, sampleValue, schemaToTs, type Operation } from './parser';

const specFile = resolve(process.argv[2] ?? process.env.SPEC_FILE ?? 'specs/jsonplaceholder.openapi.json');
const spec = loadSpec(specFile);
const ops = parseOperations(spec);

const featuresDir = resolve('features/generated');
const clientFile = resolve('src/generated/client.ts');
rmSync(featuresDir, { recursive: true, force: true });
mkdirSync(featuresDir, { recursive: true });
mkdirSync(resolve('src/generated'), { recursive: true });

function scenario(op: Operation): string {
  const given: string[] = [];
  for (const p of op.params.filter((x) => x.required && x.in !== 'header')) {
    given.push(`I set ${p.in === 'path' ? 'path' : 'query'} parameter "${p.name}" to "${String(sampleValue(p.schema))}"`);
  }
  if (op.requestSchema) {
    given.push(`I set the request body to:\n      """json\n${JSON.stringify(sampleValue(op.requestSchema), null, 2).replace(/^/gm, '      ')}\n      """`);
  }
  const then: string[] = [`the response status should be ${op.successStatus}`];
  const schema = op.responses[op.successStatus];
  if (schema) {
    then.push('the response body should match the OpenAPI schema');
    const isArray = schema.type === 'array';
    const target = isArray ? schema.items : schema;
    for (const [name, prop] of Object.entries(target?.properties ?? {}).slice(0, 10)) {
      if (prop.type && prop.type !== 'object') {
        const type = prop.type === 'integer' ? 'number' : prop.type;
        then.push(`the response JSON property "${isArray ? '[0].' : ''}${name}" should be of type "${type}"`);
      }
    }
  }
  const lines = [`  @generated @${op.operationId}`, `  Scenario: ${op.summary} (${op.key})`];
  given.forEach((s, i) => lines.push(`    ${i === 0 ? 'Given' : 'And'} ${s}`));
  lines.push(`    When I send a ${op.method} request to "${op.path}"`);
  then.forEach((s, i) => lines.push(`    ${i === 0 ? 'Then' : 'And'} ${s}`));
  return lines.join('\n');
}

function renderFeature(tag: string, tagOps: Operation[]): string {
  return `@generated @${tag}\nFeature: ${tag} API (generated from ${spec.info?.title ?? 'OpenAPI spec'})\n\n${tagOps.map(scenario).join('\n\n')}\n`;
}

const tags = [...new Set(ops.map((o) => o.tag))];
for (const tag of tags) {
  writeFileSync(resolve(featuresDir, `${tag}.feature`), renderFeature(tag, ops.filter((o) => o.tag === tag)));
}

// Typed client: one method per operation.
const methods = ops.map((op) => {
  const pathParams = op.params.filter((p) => p.in === 'path');
  const query = op.params.filter((p) => p.in === 'query');
  const fields: string[] = [];
  if (pathParams.length) fields.push(`pathParams: { ${pathParams.map((p) => `${p.name}: string | number`).join('; ')} }`);
  if (query.length) fields.push(`query?: { ${query.map((p) => `${JSON.stringify(p.name)}?: ${schemaToTs(p.schema)}`).join('; ')} }`);
  if (op.requestSchema) fields.push(`body: ${schemaToTs(op.requestSchema)}`);
  const optsType = fields.length ? `opts: { ${fields.join('; ')}; headers?: Record<string, string> }` : 'opts: { headers?: Record<string, string> } = {}';
  return `  /** ${op.key} — ${op.summary}. Success status: ${op.successStatus}. */
  ${op.operationId}(${optsType}): Promise<ApiResult> {
    return sendRequest(this.request, ${JSON.stringify(op.method)}, ${JSON.stringify(op.path)}, opts);
  }`;
});

writeFileSync(
  clientFile,
  `// AUTO-GENERATED by src/generator/generate.ts — do not edit.
import type { APIRequestContext } from '@playwright/test';
import { sendRequest, type ApiResult } from '../support/http';

export class GeneratedApi {
  constructor(private readonly request: APIRequestContext) {}

${methods.join('\n\n')}
}
`,
);

console.log(`Generated ${ops.length} operations -> ${tags.length} feature file(s) + typed client`);
